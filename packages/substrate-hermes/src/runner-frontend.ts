// The generated `scripts/runner.ts` — the CLI frontend over Hermes' kanban kernel.
//
// WHY THIS EXISTS, and it is the last piece of the native pass. The portable PM doctrine dispatches with
// `bun scripts/runner.ts launch <agent> --ref <id>`; the local substrate emits exactly such a file over its
// own Runner. Without one on Hermes the PM's only way to file work is `kanban_create` — which BYPASSES the
// review edge, because `review: <role>` is realized in `HermesRunner.launch` (it opens the linked child card
// the kernel promotes when the proposal reaches done). A PM filing cards directly would produce proposals
// that are never reviewed, while every surface still said the merge boundary existed.
//
// WHY IT IS SELF-CONTAINED (only `node:*` imports), which is the uncomfortable part. The substrate packages
// are `private: true` — they are never published — so an installed repo CANNOT resolve
// `@open-autonomy/substrate-hermes`, and a frontend that imported it would fail on its first run in every
// real install. The local substrate's frontend is self-contained for the same reason. The cost is a second
// implementation of the launch rules, which is exactly the drift the one-owner rule exists to prevent — so
// it is paid for by `runner-frontend.test.ts`, which runs BOTH this file and `HermesRunner` against a stub
// `hermes` that records its argv and asserts the two issue byte-identical kanban commands. If they ever
// diverge, that test fails; it is the seam, not a convention.
export function runnerFrontendSrc(): string {
  return `#!/usr/bin/env bun
// GENERATED by open-autonomy (substrate-hermes). Do not edit — re-run the compile.
//
// The Runner contract's verbs over Hermes' kanban kernel. Every one of them is the kernel's own:
//   launch <actor> --ref <id>   -> kanban create (+ the linked review card, when the actor declares one)
//   list [actor]                -> kanban list      (the RUNNING set: cards not done/archived)
//   get <id>                    -> kanban show
//   cancel <id>                 -> kanban reclaim (stops the worker) + archive (leaves the running set)
//
// \`--json\` on launch/list/get prints the session(s) plus this substrate's \`branch\` — ASK for a branch,
// never construct one. Hermes names a card's worktree branch itself, so a constructed \`agent/issue-<id>\`
// names nothing that exists here.
//
// Self-contained on purpose: an installed repo has no @open-autonomy packages to import. The launch rules
// below are kept honest by substrate-hermes' runner-frontend.test.ts, which asserts this file and
// HermesRunner issue identical kanban commands.
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const HERMES = process.env.HERMES_BIN ?? 'hermes';
const CWD = process.cwd();
const PARAMS_MARKER = '<!-- open-autonomy:params -->';

const argv = process.argv.slice(2);
const verb = argv[0];
const json = argv.includes('--json');

function flag(name) {
  const at = argv.indexOf(\`--\${name}\`);
  return at >= 0 ? argv[at + 1] : undefined;
}
function die(message) {
  console.error(\`runner: \${message}\`);
  process.exit(2);
}

if (argv.includes('--branch')) {
  die(
    "--branch is not accepted on the hermes substrate. The kernel owns each card's worktree and the runner " +
      'names its branch (issue ref + a per-create token); git refuses to check out one branch in two ' +
      'worktrees, so reusing a branch across cards fails the spawn and auto-blocks the card. Read a branch ' +
      'back with \`runner.ts get <id> --json\` instead of constructing one.',
  );
}

function kanban(args) {
  const r = spawnSync(HERMES, ['kanban', ...args], { cwd: CWD, encoding: 'utf8' });
  if (r.error) die(\`cannot run \\\`\${HERMES} kanban\\\` (\${r.error.message}). Set HERMES_BIN or install Hermes on PATH.\`);
  return { ok: r.status === 0, stdout: r.stdout ?? '', stderr: r.stderr ?? '' };
}

function manifestAgent(actor) {
  const path = join(CWD, '.open-autonomy', 'autonomy.json');
  if (!existsSync(path)) return undefined;
  try {
    return JSON.parse(readFileSync(path, 'utf8')).agents?.[actor];
  } catch {
    return undefined;
  }
}

/** The param this actor's trigger binds to \`subject.ref\`, so \`--ref\` lands on the DECLARED key rather
 *  than an invented one. The manifest is the authority; nothing here assigns meaning to a param. */
function refParam(actor) {
  const params = manifestAgent(actor)?.params ?? {};
  const key = Object.entries(params).find(([, source]) => source === 'subject.ref')?.[0];
  if (!key) die(\`actor "\${actor}" declares no trigger param bound to subject.ref, so --ref has nowhere to land\`);
  return key;
}

const encodeParams = (actor, params) =>
  \`Launched by open-autonomy for actor \\\`\${actor}\\\`.\\n\\n\${PARAMS_MARKER}\\n\\\`\\\`\\\`json\\n\${JSON.stringify(params, null, 2)}\\n\\\`\\\`\\\`\\n\`;
const workspaceOf = (declared) => \`\${declared?.execution?.workspace === 'isolated' ? 'worktree' : 'dir'}:\${CWD}\`;
const worktreePathOf = (cardId) => join(CWD, '.worktrees', cardId);
const branchFor = (ref) => \`\${ref}-\${Date.now().toString(36)}\`;

// Hermes resolves --idempotency-key with \`status != 'archived'\`, so a DONE card is returned as a hit with
// the same \`Created <id>\` receipt and exit 0. That silently breaks rework: after changes-requested the
// proposal card is done, so re-filing re-files nothing and the PM loops forever. A hit on a finished card
// means the key is SPENT -> retry under a discriminated key. (Mirrors HermesRunner.createCard.)
function createCard(args, what, keyed) {
  const keyAt = args.indexOf('--idempotency-key');
  for (let attempt = 1; ; attempt++) {
    const r = kanban(args);
    const id = r.stdout.match(/^Created\\s+(\\S+)/m)?.[1];
    if (!r.ok || !id) die(\`hermes kanban create failed for \${what} — \${(r.stderr || r.stdout).trim() || 'no output'}\`);
    if (keyAt < 0 || !keyed) return id;
    if (card(id)?.task?.status !== 'done') return id;
    if (attempt >= 20) {
      die(\`every idempotency key for \${what} resolves to a completed card (\${attempt} attempts). Refusing to report a launch that started nothing.\`);
    }
    args[keyAt + 1] = \`\${args[keyAt + 1].replace(/#\\d+$/, '')}#\${attempt + 1}\`;
  }
}

function launch(actor, ref) {
  const declared = manifestAgent(actor);
  const params = ref ? { [refParam(actor)]: ref } : {};
  const workspace = workspaceOf(declared);
  const args = ['create', \`open-autonomy: \${actor}\`, '--assignee', actor, '--workspace', workspace,
                '--body', encodeParams(actor, params), '--created-by', 'open-autonomy'];
  if (typeof declared?.timeout === 'number') args.push('--max-runtime', \`\${declared.timeout}m\`);
  if (ref && workspace.startsWith('worktree')) args.push('--branch', branchFor(ref));
  if (ref) args.push('--idempotency-key', \`open-autonomy:\${actor}:\${ref}\`);
  const id = createCard(args, \`actor "\${actor}"\`, !!ref);

  // The merge boundary, opened structurally at launch. The reviewer is placed in the PROPOSAL'S OWN
  // worktree (idle by the time the kernel releases this card), so it stands on the branch it reviews and
  // its verdict commits beside the evidence rather than colliding with it on trunk.
  const reviewer = declared?.review;
  if (reviewer) {
    const rd = manifestAgent(reviewer);
    const rws =
      rd?.execution?.workspace !== 'isolated' && declared?.execution?.workspace === 'isolated'
        ? \`dir:\${worktreePathOf(id)}\`
        : workspaceOf(rd);
    const rargs = ['create', \`open-autonomy: \${reviewer} of \${actor}\${ref ? \` (\${ref})\` : ''}\`,
                   '--assignee', reviewer, '--parent', id, '--workspace', rws,
                   '--body', encodeParams(reviewer, params), '--created-by', 'open-autonomy'];
    // Keyed on the PARENT too: a review card belongs to one proposal. Keyed on the ref alone, a re-filed
    // proposal adopts the PREVIOUS proposal's review card — parented to the dead card, released by ITS
    // archival, so the new proposal ships unreviewed while rc=0 says the edge was opened.
    if (ref) rargs.push('--idempotency-key', \`open-autonomy:\${reviewer}:\${ref}:\${id}\`);
    const r = kanban(rargs);
    if (!r.ok) {
      // Loud, never best-effort: a launch that quietly loses its review edge is a merge boundary that
      // stopped existing while every surface still says it is there.
      die(
        \`launched "\${actor}" as card \${id} but could not open its "\${reviewer}" review card — \` +
          \`\${(r.stderr || r.stdout).trim() || 'no output'}. The proposal card exists and is UNREVIEWED; \` +
          \`cancel it (\\\`runner.ts cancel \${id}\\\`) or open the review card by hand.\`,
      );
    }
  }
  return id;
}

function card(id) {
  const r = kanban(['show', id, '--json']);
  if (!r.ok) return undefined;
  try {
    return JSON.parse(r.stdout);
  } catch {
    return undefined;
  }
}

const RUNNING = new Set(['triage', 'todo', 'scheduled', 'ready', 'running', 'review', 'blocked']);
const sessionOf = (t) => ({
  id: t.id,
  agent: t.assignee ?? '',
  status: t.status === 'blocked' ? 'paused' : t.status === 'done' ? 'done' : t.status === 'archived' ? 'cancelled' : 'running',
  ref: t.id,
  branch: t.branch_name ?? null,
  card: t.status,
});

switch (verb) {
  case 'launch': {
    const actor = argv[1];
    if (!actor || actor.startsWith('--')) die('usage: runner.ts launch <actor> [--ref <issue-id>] [--json]');
    const id = launch(actor, flag('ref'));
    const t = card(id)?.task;
    console.log(json ? JSON.stringify(t ? sessionOf(t) : { id, agent: actor, status: 'running', ref: id, branch: null }) : \`launched \${actor} as \${id}\`);
    break;
  }
  case 'list': {
    const actor = argv[1] && !argv[1].startsWith('--') ? argv[1] : undefined;
    const r = kanban(['list', '--json']);
    let cards = [];
    try {
      cards = JSON.parse(r.stdout);
    } catch { /* an unreadable board lists nothing rather than crashing a tick */ }
    const sessions = cards.filter((t) => RUNNING.has(t.status)).map(sessionOf).filter((s) => !actor || s.agent === actor);
    if (json) console.log(JSON.stringify(sessions));
    else if (!sessions.length) console.log(\`(no running sessions\${actor ? \` for \${actor}\` : ''})\`);
    else for (const s of sessions) console.log(\`\${s.id}  \${s.agent}  \${s.card}\${s.branch ? \`  \${s.branch}\` : ''}\`);
    break;
  }
  case 'get': {
    const id = argv[1];
    if (!id) die('usage: runner.ts get <id> [--json]');
    const t = card(id)?.task;
    if (!t) die(\`no such session \${id}\`);
    console.log(JSON.stringify(sessionOf(t), null, json ? 0 : 2));
    break;
  }
  case 'cancel': {
    const id = argv[1];
    if (!id) die('usage: runner.ts cancel <id>');
    // Children first: a cancelled proposal must take its review card with it, or the review sits in \`todo\`
    // forever waiting on a parent that will never reach done.
    for (const child of card(id)?.children ?? []) {
      kanban(['reclaim', child, '--reason', 'parent cancelled by the open-autonomy runner']);
      kanban(['archive', child]);
    }
    kanban(['reclaim', id, '--reason', 'cancelled by the open-autonomy runner']);
    const ok = kanban(['archive', id]).ok;
    console.log(ok ? \`cancelled \${id}\` : \`could not cancel \${id}\`);
    process.exit(ok ? 0 : 1);
  }
  default:
    die('usage: runner.ts <launch|list|get|cancel> ...  (see the file header)');
}
`;
}
